    print("测试脚本: 向职位库插入 20 个 Python / AI Agent 方向职位")
    print("=" * 60)

    # 先检查后端是否可用
    try:
        r = requests.get(f"{API_BASE}/health", timeout=5)
        r.raise_for_status()
    except Exception:
        print("错误: 后端服务不可用,请确保运行在 http://127.0.0.1:8000")
        sys.exit(1)

    total = len(POSITIONS)
    success_count = 0
    for i, payload in enumerate(POSITIONS, 1):
        name = payload["name"]

        try:
            r = requests.post(f"{API_BASE}/positions", json=payload, timeout=TIMEOUT)
            r.raise_for_status()
            result = r.json()
            if result.get("success"):
                pid = result["position"]["id"]
                print(f"  [{i:2d}/{total}] {name} -> {pid}")
                success_count += 1
            else:
                print(f"  [{i:2d}/{total}] {name} -> 失败: {result}")
        except Exception as e:
            print(f"  [{i:2d}/{total}] {name} -> 异常: {e}")

        time.sleep(0.1)  # 避免请求过快

    print(f"\n完成: {success_count}/{total} 个职位插入成功")
    if success_count == total:
        print("可在前端职位库页面查看全部职位")


